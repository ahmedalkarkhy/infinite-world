function applyLang(lang) {
  const dict = I18N[lang] || I18N[DEFAULT_LANG];
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const v = dict[el.getAttribute("data-i18n")];
    if (v != null) el.textContent = v;
  });
  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    const v = dict[el.getAttribute("data-i18n-html")];
    if (v != null) el.innerHTML = v;
  });
  // Legal pages are one file per language, so their links move with the toggle
  document.querySelectorAll("[data-i18n-href]").forEach((el) => {
    const v = dict[el.getAttribute("data-i18n-href")];
    if (v != null) el.setAttribute("href", v);
  });
  const t = document.getElementById("langToggle");
  if (t) {
    t.innerHTML =
      lang === "en"
        ? "<b>EN</b><span>/ PT</span>"
        : "<b>PT</b><span>/ EN</span>";
  }
  try {
    localStorage.setItem("iw_lang", lang);
  } catch (e) {}
}

const DEFAULT_LANG = "pt";

(function initLang() {
  let lang = DEFAULT_LANG;
  try {
    lang = localStorage.getItem("iw_lang") || DEFAULT_LANG;
  } catch (e) {}
  const run = () => {
    applyLang(lang);
    const t = document.getElementById("langToggle");
    if (t)
      t.addEventListener("click", () => {
        applyLang(document.documentElement.lang === "en" ? "pt" : "en");
      });
  };
  if (document.readyState === "loading")
    document.addEventListener("DOMContentLoaded", run);
  else run();
})();
